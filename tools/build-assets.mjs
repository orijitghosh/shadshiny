// Bundles inst/assets into a single minified CSS and JS file.
//
// Without this, a page carries one <link> per component stylesheet and one
// <script> per component behaviour: ~145 tags and 1.3 MB of source. The bundle
// is committed, so installing the R package never needs Node.
//
// Run: npm run build:assets
//
// The load order here must match shad_asset_css_order() / shad_asset_js_order()
// in R/deps.R. dist/manifest.json records what went in, and
// tests/testthat/test-assets.R fails if the two ever drift apart.

import { readdirSync, readFileSync, mkdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { transform } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assets = join(root, "inst", "assets");
const dist = join(assets, "dist");

const components = readdirSync(join(assets, "components"), { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const exists = (rel) => existsSync(join(assets, rel));
const cssFor = (name) => `components/${name}/${name}.css`;
const jsFor = (name) => `components/${name}/${name}.js`;

// tokens -> base -> animations -> dropdown-menu (shared .shad-menu*) -> rest
const cssOrder = [
  "tokens/shad-tokens.css",
  "core/shad-base.css",
  "core/shad-animations.css",
  cssFor("dropdown-menu"),
  ...components.filter((n) => n !== "dropdown-menu").map(cssFor),
].filter(exists);

// runtime -> dialog -> alert-dialog -> dropdown-menu -> rest -> shiny binding
const jsHead = ["dialog", "alert-dialog", "dropdown-menu"];
const jsOrder = [
  "core/shad-runtime.js",
  ...jsHead.map(jsFor),
  ...components.filter((n) => !jsHead.includes(n)).map(jsFor),
].filter(exists);
jsOrder.push("shiny/shadshiny-shiny.js");

const concat = (paths) =>
  paths.map((p) => `/* ${p} */\n${readFileSync(join(assets, p), "utf8")}`).join("\n");

const banner = (kind) =>
  `/*! shadshiny bundled ${kind} -- generated by tools/build-assets.mjs, do not edit */\n`;

const css = await transform(concat(cssOrder), { loader: "css", minify: true });
const js = await transform(concat(jsOrder), { loader: "js", minify: true });

mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, "shadshiny.min.css"), banner("css") + css.code);
writeFileSync(join(dist, "shadshiny.min.js"), banner("js") + js.code);
writeFileSync(
  join(dist, "manifest.json"),
  JSON.stringify({ css: cssOrder, js: jsOrder }, null, 2) + "\n"
);

const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(0)} kB`;
console.log(`css: ${cssOrder.length} files -> ${kb(css.code)}`);
console.log(`js:  ${jsOrder.length} files -> ${kb(js.code)}`);
